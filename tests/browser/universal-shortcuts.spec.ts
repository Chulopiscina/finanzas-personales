import { expect, test } from "@playwright/test";
test.skip(!process.env.TEST_APP_URL, "Solo base ficticia local.");

test("iPhone universal: bancos desde la web y aviso sin identidad pendiente de asignación", async ({ page }, info) => {
  await page.goto("/login");
  await page.getByLabel("Correo electrónico").fill(process.env.E2E_EMAIL!);
  await page.getByLabel("Contraseña", { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Hola Auditoría/ })).toBeVisible();
  const initial = await (await page.request.get("/api/dashboard")).json();
  const accounts = (await (await page.request.get("/api/accounts")).json()).accounts;
  const account = accounts.find((a: { name: string }) => a.name === "Cuenta de prueba");
  const savings = accounts.find((a: { name: string }) => a.name === "Ahorro de prueba");
  const pairingResponse = await page.request.post("/api/integrations/shortcuts/pairing", { headers: { Origin: process.env.TEST_APP_URL! }, data: { accountId: account.id, bankId: "bbva", consent: true } });
  expect(pairingResponse.status()).toBe(200);
  const pairing = await pairingResponse.json();
  const setup = JSON.parse(new URL(pairing.setupUrl).searchParams.get("text")!);
  const exchanged = await (await page.request.post("/api/integrations/shortcuts/pairing/exchange", { data: { code: setup.code } })).json();
  await page.goto("/notifications");
  const device = page.getByTestId("shortcut-device-" + exchanged.deviceId);
  await device.getByRole("button", { name: "Gestionar bancos" }).click();
  const modal = page.getByRole("dialog");
  await modal.getByLabel("Banco vinculado").selectOption("ing");
  await modal.getByLabel("Cuenta vinculada").selectOption(savings.id);
  await modal.getByRole("button", { name: "Guardar vinculación" }).click();
  await expect(modal).toBeHidden();
  await expect(device.getByText("ING · Ahorro de prueba", { exact: true })).toBeVisible();
  await page.reload();
  await expect(device.getByText("ING · Ahorro de prueba", { exact: true })).toBeVisible();
  const body = "Pago sin banco identificado 9,99 EUR " + info.project.name;
  const received = await page.request.post("/api/integrations/shortcuts/events", { headers: { Authorization: "Bearer " + exchanged.token }, data: { eventId: crypto.randomUUID(), body } });
  expect(received.status()).toBe(202);
  await page.reload();
  const event = page.locator("li").filter({ hasText: body });
  await expect(event.getByText(/Cuenta pendiente/)).toBeVisible();
  await event.getByRole("button", { name: "Asignar cuenta" }).click();
  await modal.getByLabel("Cuenta del aviso").selectOption(account.id);
  page.once("dialog", d => d.accept());
  await modal.getByRole("button", { name: "Confirmar cuenta" }).click();
  await expect(modal).toBeHidden();
  await expect(event.getByRole("button", { name: "Conciliar", exact: true })).toBeVisible();
  await page.reload();
  await expect(event.getByText(/Cuenta de prueba/)).toBeVisible();
  const after = await (await page.request.get("/api/dashboard")).json();
  expect(after.metrics).toEqual(initial.metrics);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("universal-notifications.png"), fullPage: true });
});
