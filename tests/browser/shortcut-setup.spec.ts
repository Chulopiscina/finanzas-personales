import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
const universalICloud = JSON.parse(readFileSync(new URL("../../shortcuts/universal-icloud.json", import.meta.url), "utf8"));

test.skip(!process.env.TEST_SHORTCUT_SETUP_ONLY, "Solo servidor local con recepción desactivada.");
test("instala y vincula desde el asistente, sin tokens manuales ni notificaciones", async ({ page }, info) => {
  await page.goto("/login");
  await page.getByLabel("Correo electrónico").fill(process.env.E2E_EMAIL!);
  await page.getByLabel("Contraseña", { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Hola Auditoría/ })).toBeVisible();
  const before = (await (await page.request.get("/api/dashboard")).json()).metrics;
  await page.goto("/notifications");
  await expect(page.getByText(/Recepción desactivada\. Puedes instalar/)).toBeVisible();
  await expect(page.getByText("Configuración avanzada", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Conectar banco", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Banco para conectar").selectOption("bbva");
  const accounts = (await (await page.request.get("/api/accounts")).json()).accounts;
  const account = accounts.find((a: { name: string }) => a.name === "Cuenta de prueba");
  await dialog.getByLabel("Cuenta bancaria").selectOption(account.id);
  await dialog.getByRole("checkbox").check();
  await dialog.getByRole("button", { name: "Continuar", exact: true }).click();
  await expect(dialog.getByRole("link", { name: "Instalar atajo" })).toHaveAttribute("href", universalICloud.installUrl);
  await dialog.getByRole("button", { name: "Ya lo he añadido" }).click();
  const nativeLink = dialog.getByRole("link", { name: "Vincular este iPhone" });
  await expect(nativeLink).toBeVisible();
  const setup = JSON.parse(new URL((await nativeLink.getAttribute("href"))!).searchParams.get("text")!);
  expect(setup.version).toBe(2);
  expect(new URL((await nativeLink.getAttribute("href"))!).searchParams.get("name")).toBe("Finanzas Bancarias");
  // Simulate the native protocol, not Apple installation or execution on an iPhone.
  const response = await page.request.post("/api/integrations/shortcuts/pairing/exchange", { data: { code: setup.code } });
  expect(response.status()).toBe(200);
  const device = await response.json();
  expect((await page.request.post("/api/integrations/shortcuts/check", { headers: { Authorization: "Bearer " + device.token } })).status()).toBe(200);
  await page.goto("/notifications?pairing=" + device.pairingId);
  await expect(page.getByText("Conexión comprobada. La recepción de notificaciones sigue desactivada.")).toBeVisible();
  await page.getByRole("button", { name: "Finalizar vinculación" }).click();
  await expect(page.getByRole("heading", { name: "Tu conexión está preparada" })).toBeVisible();
  await expect(page.getByText(/No actives todavía la automatización/)).toBeVisible();
  await page.getByRole("button", { name: "Volver a mis notificaciones" }).click();
  const rejected = await page.request.post("/api/integrations/shortcuts/events", { headers: { Authorization: "Bearer " + device.token }, data: { eventId: crypto.randomUUID(), body: "BBVA: Pago 10 EUR" } });
  expect(rejected.status()).toBe(503);
  const row = page.getByTestId("shortcut-device-" + device.deviceId);
  await row.getByRole("button", { name: "Gestionar bancos" }).click();
  await page.getByRole("dialog").getByLabel("Banco vinculado").selectOption("ing");
  await page.getByRole("dialog").getByLabel("Cuenta vinculada").selectOption(account.id);
  await page.getByRole("button", { name: "Guardar vinculación" }).click();
  await expect(row.getByText("ING · Cuenta de prueba", { exact: true })).toBeVisible();
  page.once("dialog", d => d.accept());
  await row.getByRole("button", { name: "Desconectar" }).click();
  await expect(row.getByText("Desconectado", { exact: true })).toBeVisible();
  expect((await page.request.post("/api/integrations/shortcuts/check", { headers: { Authorization: "Bearer " + device.token } })).status()).toBe(401);
  expect((await (await page.request.get("/api/dashboard")).json()).metrics).toEqual(before);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("setup-receipt-paused.png"), fullPage: true });
});
